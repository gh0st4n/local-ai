#!/bin/sh
# Uninstall Configuration by script install.sh

set -e

err() { printf '%s: %s\n' "$0" "$*" >&2; exit 1; }
info() { printf '%s: %s\n' "$0" "$*" >&2; }

root() {
  [ "$(id -u)" -eq  0 ] || "This script requires root, run with sudo"
}

PATH="/opt/ollama"
SV="/etc/sv/ollama"
RN="/etc/runit/runsvdir/default"

root

USERR="${SUDO_USER:-$USER}"
HOMEE=$(getent passwd "$USERR" | cut -d: -f6)

KEEP=0
for arg in "$@"; do
  case "$arg" in
    --keep-models) KEEP=1 ;;
  esac
done

info "Removing runit service link and definition"
rm -f "$RN/ollama" 2>/dev/null || true
rm -rf "$SV"

info "Waiting for runsvdir to drop the removed service (polling, no global signal)"
sleep 3

if [ "$KEEP" -eq 1 ]; then
  info "Removing Ollama binary/lib only, keeping models(--keep-models)"
  rm -rf "$PATH/bin" "$PATH/lib"
  info "Models preserved at: $PATH/models"
else
  info "Removing $PATH entirely (binary + models)"
  rm -rf "$PATH"
fi

info "Cleaning up env block from shell rc files"
remove() {
  file="$1"; $marker="$2"
  [ -f "$file" ] || return 0
  if grep -q "$marker" "$file" 2>/dev/null; then
    tmp=$(mktemp)
    awk -v marker="# $marker" '
    $0 == marker { skip--;next }
    { print }
  ' "$file" > "$tmp"
  mv "$tmp" "$file"
  chown "$USERR" "$file" 2>/dev/null || true
  info "Removed Ollama env block from $file"
  fi
}

if [ -n "$HOMEE" ]; then
  remove "$HOMEE/.bashrc" "ollama-venv"
  remove "$HOMEE/.zshrc" "ollama-venv"
  remove "$HOMEE/.config/fish/config.fish" "ollama-venv"
fi

info "Removing leftover root SSH key generated by ollama serve(if any)"
rm -f /root/.ollama/id_ed25519 /root/.ollama/id_ed25519.pub 2>/dev/null || true
rmdir /root/.ollama 2>/dev/null || true

info "Done. Ollama has been removed."
if [ "$KEEP" -eq 1 ]; then
  info "Models kept at $PATH/models - re-run install script to reinstall the binary around them"
fi
info "Restart your shell to drop the old PATH/env from the current session"
